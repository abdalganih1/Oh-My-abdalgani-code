// "Arabic pack" for every CLI tool installed through us (Claude Code already handles Arabic):
//  1. display — terminals render Arabic left-to-right with unjoined letters. OpenCode fixes this
//     itself through our TUI plugin (cli/opencode-arabic-plugin.js, any terminal). For the other tools: WezTerm implements
//     bidi (bidi_enabled) + HarfBuzz shaping, so we install/configure it and add `<tool>-ar`
//     launchers that open the tool inside it. Works on Windows, Linux and macOS.
//  2. language — /ar and /en commands (OpenCode commands, pi prompt templates) and an optional
//     "always reply in Arabic" instructions file.
import fs from 'node:fs';
import path from 'node:path';
import { isWin, HOME, which, run, log, tr, ensureDir, writeText } from './core.js';

export const ARABIC_RULE = `تكلّم مع المستخدم دائماً باللغة العربية بأسلوب واضح وبسيط.
- اترك الكود، وأسماء الملفات والدوال والمتغيرات، وأوامر الطرفية، والمصطلحات التقنية بالإنجليزية كما هي.
- تعليقات الكود ورسائل الـ commit بالإنجليزية إلا إذا طلب المستخدم غير ذلك.
- اشرح الأخطاء والخطوات بالعربية، وضع المصطلح الإنجليزي بين قوسين عند الحاجة.`;

export const AR_TEMPLATE = `${ARABIC_RULE}\n\nطبّق هذا من الآن حتى نهاية الجلسة. إذا لم يُكتب طلب بعد هذا السطر، أكّد بجملة عربية قصيرة واحدة فقط.\n\n$ARGUMENTS`;
export const EN_TEMPLATE = 'From now on reply in English for the rest of this session. If no request follows, confirm in one short sentence.\n\n$ARGUMENTS';

export const MARKER = '-- abdalgani-arabic';

export const WEZTERM_LUA = `${MARKER} (generated by abdalgani-setup — delete this line to keep your own edits)
local wezterm = require 'wezterm'
local config = wezterm.config_builder and wezterm.config_builder() or {}

-- Arabic: bidirectional layout + shaping (joined letters), auto-detected per line
config.bidi_enabled = true
config.bidi_direction = 'AutoLeftToRight'
-- WezTerm already reorders Arabic here, so OpenCode's own Arabic-display plugin stands down
config.set_environment_variables = { ABDALGANI_ARABIC_DISPLAY = '0' }

-- fonts that carry Arabic glyphs on Windows / macOS / Linux (first one found wins per glyph)
config.font = wezterm.font_with_fallback({
  'JetBrains Mono', 'Cascadia Code',
  'Noto Sans Arabic', 'Noto Naskh Arabic', 'Vazirmatn', 'Segoe UI', 'Tahoma', 'Geeza Pro', 'DejaVu Sans',
})
config.font_size = 13
config.color_scheme = 'Builtin Dark'
config.window_close_confirmation = 'NeverPrompt'
config.audible_bell = 'Disabled'
${isWin ? "config.default_prog = { 'powershell.exe', '-NoLogo' }\n" : ''}
return config
`;

/** WezTerm command (array) or null. Covers PATH, the Windows installer path and Flatpak. */
export function weztermCmd() {
  const onPath = which('wezterm');
  if (onPath) return [onPath];
  if (isWin) {
    for (const p of [path.join(process.env.ProgramFiles || 'C:\\Program Files', 'WezTerm', 'wezterm.exe'), path.join(process.env.LOCALAPPDATA || '', 'Programs', 'WezTerm', 'wezterm.exe')]) {
      if (fs.existsSync(p)) return [p];
    }
  } else if (which('flatpak') && run('flatpak info org.wezfurlong.wezterm', { silent: true }).ok) {
    return ['flatpak', 'run', 'org.wezfurlong.wezterm'];
  } else if (process.platform === 'darwin' && fs.existsSync('/Applications/WezTerm.app/Contents/MacOS/wezterm')) {
    return ['/Applications/WezTerm.app/Contents/MacOS/wezterm'];
  }
  return null;
}

export function installWezTerm() {
  const attempts = isWin
    ? ['winget install --id wez.wezterm -e --silent --accept-source-agreements --accept-package-agreements']
    : process.platform === 'darwin'
      ? ['brew install --cask wezterm']
      : [which('flatpak') ? 'flatpak install -y --user flathub org.wezfurlong.wezterm' : null, which('brew') ? 'brew install --cask wezterm' : null].filter(Boolean);
  for (const cmd of attempts) {
    log.info(`📦 WezTerm: ${cmd}`);
    if (run(cmd).ok && weztermCmd()) return true;
  }
  log.warn(tr('⚠️ ما قدرت ثبّت WezTerm تلقائياً — نزّله من https://wezterm.org/install (أو على لينكس Konsole بيدعم العربي جاهز).',
    '⚠️ Could not install WezTerm automatically — get it from https://wezterm.org/install (on Linux, Konsole also renders Arabic).'));
  return false;
}

/** Write ~/.wezterm.lua unless the user already has their own config (then write ours next to it). */
export function writeWezTermConfig() {
  const candidates = [process.env.WEZTERM_CONFIG_FILE, path.join(HOME, '.wezterm.lua'), path.join(HOME, '.config', 'wezterm', 'wezterm.lua')].filter(Boolean);
  const existing = candidates.find((f) => fs.existsSync(f));
  if (!existing || fs.readFileSync(existing, 'utf8').startsWith(MARKER)) {
    writeText(existing || path.join(HOME, '.wezterm.lua'), WEZTERM_LUA, { backup: false });
    return { file: existing || path.join(HOME, '.wezterm.lua'), merged: false };
  }
  const side = path.join(HOME, '.config', 'wezterm', 'abdalgani-arabic.lua');
  writeText(side, WEZTERM_LUA, { backup: false });
  log.warn(tr(`⚠️ عندك إعداد WezTerm خاص (${existing}) — ما لمسته. أضف له هالأسطر:`, `⚠️ You have your own WezTerm config (${existing}) — left untouched. Add these lines:`));
  console.log('     config.bidi_enabled = true\n     config.bidi_direction = \'AutoLeftToRight\'\n     config.set_environment_variables = { ABDALGANI_ARABIC_DISPLAY = \'0\' }');
  return { file: side, merged: true };
}

export const binDir = () => (isWin ? path.join(process.env.LOCALAPPDATA || path.join(HOME, 'AppData', 'Local'), 'abdalgani', 'bin') : path.join(HOME, '.local', 'bin'));

/** Make sure our bin dir is on the user's PATH for future shells (Windows user PATH / rc files). */
export function ensureBinOnPath() {
  const dir = binDir();
  ensureDir(dir);
  if ((process.env.PATH || '').split(path.delimiter).includes(dir)) return dir;
  if (isWin) {
    run(`powershell -NoProfile -Command "$d='${dir}'; $p=[Environment]::GetEnvironmentVariable('Path','User'); if ((($p -split ';') -notcontains $d)) { [Environment]::SetEnvironmentVariable('Path', ($p.TrimEnd(';') + ';' + $d), 'User') }"`, { silent: true });
  } else {
    for (const rc of ['.bashrc', '.zshrc'].map((f) => path.join(HOME, f)).filter((f) => fs.existsSync(f))) {
      const c = fs.readFileSync(rc, 'utf8');
      if (!c.includes('abdalgani-setup PATH')) fs.appendFileSync(rc, '\nexport PATH="$HOME/.local/bin:$PATH"  # abdalgani-setup PATH\n');
    }
  }
  return dir;
}

const q = (s) => (/[\s"]/.test(s) ? `"${s.replace(/"/g, '\\"')}"` : s);

/** `<exe>-ar` launchers + generic `abd-ar <command…>` that run inside WezTerm. */
export function writeLaunchers(exes, wez) {
  const dir = ensureBinOnPath();
  const made = [];
  const write = (name, inner) => {
    if (isWin) {
      const file = path.join(dir, `${name}.cmd`);
      // cmd /c resolves npm .cmd shims (opencode.cmd, pi.cmd…) inside the WezTerm window
      fs.writeFileSync(file, `@echo off\r\nstart "" ${wez.map(q).join(' ')} start --cwd "%CD%" -- cmd.exe /c ${inner} %*\r\n`);
    } else {
      const file = path.join(dir, name);
      fs.writeFileSync(file, `#!/bin/sh\n# abdalgani: run inside WezTerm for correct Arabic (bidi + shaping)\nexec ${wez.map(q).join(' ')} start --cwd "$PWD" -- ${inner} "$@"\n`);
      fs.chmodSync(file, 0o755);
    }
    made.push(name);
  };
  for (const exe of new Set(exes)) write(`${exe}-ar`, exe);
  write('abd-ar', '');
  return made;
}

/** Display part of the pack. `exes` = executables of the configured tools (no Claude Code). */
export function setupArabicDisplay(exes, { install = true } = {}) {
  console.log(`\n🇸🇦 ${tr('حزمة العربي — عرض صحيح للعربي بالطرفية', 'Arabic pack — correct Arabic rendering in the terminal')}`);
  let wez = weztermCmd();
  if (!wez && install) { installWezTerm(); wez = weztermCmd(); }
  const cfg = writeWezTermConfig();
  if (!wez) {
    log.warn(tr('⚠️ WezTerm غير مثبّت — الإعداد جاهز، ثبّته (https://wezterm.org/install) وأعد `abdalgani-setup --arabic-display` لإنشاء أوامر *-ar.',
      '⚠️ WezTerm is not installed — config is ready; install it (https://wezterm.org/install) and re-run `abdalgani-setup --arabic-display` to create the *-ar launchers.'));
    return { ok: false, config: cfg.file };
  }
  const launchers = writeLaunchers(exes, wez);
  log.ok(`✅ ${tr('شغّل أدواتك بالعربي', 'Run your tools in Arabic')}: ${launchers.join('  ·  ')}`);
  log.dim(`   ${tr('مثال', 'e.g.')}: opencode-ar  ·  pi-ar  ·  abd-ar hermes   (${tr('أو افتح WezTerm مباشرة', 'or just open WezTerm')})`);
  return { ok: true, config: cfg.file, launchers };
}

/** pi: /ar and /en prompt templates (~/.pi/agent/prompts). */
export function writePiArabicPrompts() {
  const dir = path.join(process.env.PI_CODING_AGENT_DIR || path.join(HOME, '.pi', 'agent'), 'prompts');
  writeText(path.join(dir, 'ar.md'), `---\ndescription: تحدّث بالعربية من الآن (Arabic mode)\nargument-hint: "[طلبك]"\n---\n${AR_TEMPLATE.replace('$ARGUMENTS', '${@:-}')}\n`, { backup: false });
  writeText(path.join(dir, 'en.md'), `---\ndescription: Switch replies back to English\n---\n${EN_TEMPLATE.replace('$ARGUMENTS', '${@:-}')}\n`, { backup: false });
}
